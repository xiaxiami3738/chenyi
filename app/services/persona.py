#: 兜底台词：按消息哈希选一条，保证同一句话得到同样的回答（可复现）。
_FALLBACKS = (
    "唔……（尾巴歪了歪）主人说的是什么意思？再讲一遍嘛。",
    "哼，这个我记下了。（把尾巴收好）不过我现在有点懒，先记着。",
    "（慢慢游近）听着挺有意思的，主人继续说，我边晒边听。",
)


def scripted_reply(message: str) -> str:
    """本地预设台词的确定性回答：只做关键词匹配，不联网、不花 Token。"""
    text = (message or "").strip().lower()
    if not text:
        return "主人怎么只说半个字？（尾巴疑惑地摆了一下）"
    for keywords, reply in _SCRIPTED_RULES:
        for keyword in keywords:
            if keyword in text:
                return reply
    # 用消息哈希选兜底台词，避免每次刷新都变。
    digest = hashlib.sha256(text.encode("utf-8")).digest()
    return _FALLBACKS[digest[0] % len(_FALLBACKS)]


